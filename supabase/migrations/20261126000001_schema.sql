-- ---------------------------------------------------------------------------
-- Profiles (one per auth user)
-- ---------------------------------------------------------------------------
create table public.profiles (
  id             uuid primary key references auth.users on delete cascade,
  display_name   text check (char_length(display_name) <= 60),
  role           public.user_role not null default 'user',
  preferred_lang text not null default 'ar' check (preferred_lang in ('ar', 'fr', 'nl', 'en')),
  created_at     timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Listings
-- Free listing shows name, address, phone, category (+ Google rating).
-- Premium adds logo, gallery (max 8), description, offer line, website, badge.
-- Listings are never deleted when premium ends; only the extras are hidden.
-- ---------------------------------------------------------------------------
create table public.listings (
  id                bigint generated by default as identity primary key,
  slug              text not null unique,
  name              text not null check (char_length(name) between 2 and 200),
  category          text not null references public.categories on update cascade,
  type_label        text,
  province          text not null references public.provinces on update cascade,
  city              text,
  address           text,
  phone             text,
  website           text,
  rating_google     numeric(2,1) check (rating_google between 0 and 5),
  reviews_google    int not null default 0 check (reviews_google >= 0),
  lat               double precision,
  lng               double precision,
  languages         text[] not null default '{}',
  language_verified boolean not null default true,
  status            public.listing_status not null default 'pending',
  is_premium        boolean not null default false,
  premium_until     timestamptz,             -- null + is_premium = no expiry (granted by admin)
  is_verified       boolean not null default false,
  logo_path         text,                    -- storage path in bucket listing-photos
  description       jsonb not null default '{}'::jsonb,   -- {"ar": "...", "fr": "..."}
  offer_text        jsonb not null default '{}'::jsonb,
  owner_id          uuid references auth.users on delete set null,
  source            public.listing_source not null,
  app_rating_avg    numeric(3,2),
  app_reviews_count int not null default 0,
  search_doc        text generated always as (
                      public.normalize_text(coalesce(name, '') || ' ' || coalesce(city, '') || ' ' ||
                                            coalesce(type_label, '') || ' ' || coalesce(address, ''))
                    ) stored,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index listings_filter_idx  on public.listings (status, category, province);
create index listings_premium_idx on public.listings (is_premium, premium_until) where is_premium;
create index listings_owner_idx   on public.listings (owner_id) where owner_id is not null;
create index listings_search_idx  on public.listings using gin (search_doc extensions.gin_trgm_ops);

