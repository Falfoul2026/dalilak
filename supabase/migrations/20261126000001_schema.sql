create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger listings_touch      before update on public.listings      for each row execute function public.touch_updated_at();
create trigger reviews_touch       before update on public.reviews       for each row execute function public.touch_updated_at();
create trigger subscriptions_touch before update on public.subscriptions for each row execute function public.touch_updated_at();

-- New auth user -> profile row.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name, preferred_lang)
  values (
    new.id,
    nullif(left(new.raw_user_meta_data ->> 'display_name', 60), ''),
    case when new.raw_user_meta_data ->> 'lang' in ('ar', 'fr', 'nl', 'en')
         then new.raw_user_meta_data ->> 'lang' else 'ar' end
  )
  on conflict (id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Keep app rating columns in sync with visible reviews.
create or replace function public.refresh_listing_rating()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  lid bigint := coalesce(new.listing_id, old.listing_id);
begin
  update public.listings l
     set app_rating_avg    = s.avg_stars,
         app_reviews_count = s.n
    from (select round(avg(stars)::numeric, 2) as avg_stars, count(*)::int as n
            from public.reviews where listing_id = lid and status = 'visible') s
   where l.id = lid;
  return null;
end $$;

create trigger reviews_rating_sync
  after insert or update of stars, status or delete on public.reviews
  for each row execute function public.refresh_listing_rating();

-- Max 1 logo + 8 gallery photos per listing (pending + approved).
create or replace function public.check_photo_limit()
returns trigger language plpgsql set search_path = '' as $$
declare
  n int;
begin
  select count(*) into n from public.listing_photos
   where listing_id = new.listing_id and kind = new.kind and status <> 'rejected';
  if new.kind = 'gallery' and n >= 8 then
    raise exception 'photo_limit: max 8 gallery photos' using errcode = 'check_violation';
  elsif new.kind = 'logo' and n >= 1 then
    raise exception 'photo_limit: max 1 logo' using errcode = 'check_violation';
  end if;
  return new;
end $$;

create trigger listing_photos_limit
  before insert on public.listing_photos
  for each row execute function public.check_photo_limit();
