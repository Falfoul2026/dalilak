-- Dalilak – 0001 schema: types, tables, indexes, triggers.
-- Supabase installs extensions in the "extensions" schema.

create schema if not exists extensions;
create extension if not exists pg_trgm  with schema extensions;
create extension if not exists unaccent with schema extensions;

-- ---------------------------------------------------------------------------
-- Text normalisation used for search (Latin accents + Arabic letter variants).
-- unaccent() is not immutable, so we wrap it with a fixed dictionary.
-- ---------------------------------------------------------------------------
create or replace function public.normalize_text(t text)
returns text
language sql immutable parallel safe
set search_path = ''
as $$
  select regexp_replace(
           translate(
             lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(t, ''))),
             'أإآٱىةـ',        -- alef variants, alef maqsura, ta marbuta, tatweel
             'اااايه'           -- (tatweel has no counterpart, so it is removed)
           ),
           '[ً-ْ]', '', 'g')  -- Arabic diacritics (tashkeel)
$$;

-- URL slug: latin letters and digits only. Arabic-only names get an empty slug
-- and the caller falls back to "listing-<id>".
create or replace function public.slugify(t text)
returns text
language sql immutable parallel safe
set search_path = ''
as $$
  select trim(both '-' from regexp_replace(
           lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(t, ''))),
           '[^a-z0-9]+', '-', 'g'))
$$;

