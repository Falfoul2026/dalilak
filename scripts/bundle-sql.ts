// Builds supabase/setup.sql = all migrations + data import, in one file,
// so the whole database can be created by pasting it once in the Supabase SQL editor.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { buildImportSql, mapAll, type RawEntry } from './lib/mapData.ts'

const dir = 'supabase/migrations'
const parts = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
  .map((f) => `-- ===== ${f} =====\n${readFileSync(`${dir}/${f}`, 'utf8')}`)
const rows = mapAll(JSON.parse(readFileSync('data/dalilak-data.json', 'utf8')) as RawEntry[])
const out = [
  '-- Dalilak – complete database setup. GENERATED by `npm run db:bundle`; do not edit by hand.',
  '-- Run once on a NEW Supabase project (SQL Editor → New query → paste → Run).',
  '',
  ...parts,
  '-- ===== data import =====',
  buildImportSql(rows),
].join('\n')
writeFileSync('supabase/setup.sql', out)
console.log(`supabase/setup.sql: ${parts.length} migrations + ${rows.length} listings`)
